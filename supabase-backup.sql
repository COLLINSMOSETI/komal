-- Run once in the Supabase SQL Editor.
-- Komal uses its server-side service_role key for backup writes. Never put that
-- key in browser code or grant these tables to anon/authenticated users.

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  phone text not null unique,
  name text not null,
  about text not null default 'Hey there! I am using Komal.',
  photo text,
  pass_hash text not null,
  last_seen bigint,
  created bigint not null
);

create table if not exists public.convs (
  id bigint generated by default as identity primary key,
  type text not null check (type in ('direct', 'group')),
  name text,
  direct_key text unique,
  created_by bigint references public.users(id) on delete set null,
  created bigint not null
);

create table if not exists public.members (
  conv_id bigint not null references public.convs(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  last_read bigint not null default 0,
  primary key (conv_id, user_id)
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  conv_id bigint not null references public.convs(id) on delete cascade,
  sender bigint not null references public.users(id) on delete cascade,
  kind text not null check (kind in ('text', 'image')),
  body text,
  media text,
  w integer,
  h integer,
  created bigint not null,
  delivered integer not null default 0
);

create table if not exists public.media (
  file text primary key,
  uploader bigint not null references public.users(id) on delete cascade,
  created bigint not null
);

create table if not exists public.push_subs (
  endpoint text primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  p256dh text not null,
  auth text not null
);

create table if not exists public.login_events (
  id bigint generated always as identity primary key,
  user_id bigint not null,
  name text not null,
  phone text not null,
  event_type text not null check (event_type in ('login', 'signup')),
  logged_in_at timestamptz not null
);

create index if not exists idx_members_user on public.members(user_id);
create index if not exists idx_messages_conv on public.messages(conv_id, id);
create index if not exists idx_messages_media on public.messages(media);
create index if not exists idx_media_uploader on public.media(uploader);
create index if not exists idx_push_user on public.push_subs(user_id);
create index if not exists idx_login_events_logged_in_at on public.login_events(logged_in_at desc);

alter table public.users enable row level security;
alter table public.convs enable row level security;
alter table public.members enable row level security;
alter table public.messages enable row level security;
alter table public.media enable row level security;
alter table public.push_subs enable row level security;
alter table public.login_events enable row level security;

revoke all on table public.users, public.convs, public.members, public.messages,
  public.media, public.push_subs, public.login_events
  from public, anon, authenticated;

grant select, insert, update on table public.users, public.convs,
  public.members, public.messages, public.media, public.push_subs to service_role;
grant insert on table public.login_events to service_role;

revoke all on sequence public.users_id_seq, public.convs_id_seq,
  public.messages_id_seq, public.login_events_id_seq
  from public, anon, authenticated;
grant usage, select on sequence public.users_id_seq, public.convs_id_seq,
  public.messages_id_seq, public.login_events_id_seq to service_role;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'komal-backup',
