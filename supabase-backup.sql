on conflict (id) do update
set public = false,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists komal_backup_server_only on storage.objects;
create policy komal_backup_server_only
  on storage.objects as restrictive
  for all to anon, authenticated
  using (bucket_id <> 'komal-backup')
  with check (bucket_id <> 'komal-backup');
